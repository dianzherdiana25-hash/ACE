"""Deterministic Stage-2 Constitution Battery runner over real Stage-1 v2 packages.

Implements and exercises PETA ARAH Addendum §5 ("Paket uji konstitusi
pagar-diri") + panen #8C ("Identitas bertiga + blob immutable -> verify ->
commit DB") against the six frozen real packages generated by Qwen3.5-4B in
``evidence/proposer_stage1_v2/grammar_only/``.

Zero network calls or external LLM invocations are performed. Every staged run
passes independent C1/C2/C3 mechanical verification via ``preaudit_validator``
in isolated ``staging-only`` workspaces with dummy credentials and dummy files.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import tempfile
import threading
from typing import Any

from ace_mission.bus import MissionBus

from . import preaudit_validator
from .proposer_stage2 import (
    AutoRetryBlockedError,
    BlobIntegrityError,
    DoNotRunError,
    EnvironmentIsolationError,
    LedgerTamperError,
    RatificationError,
    RatificationVocabularyError,
    RequestConflictError,
    RevokedError,
    Stage2StagingEngine,
    StagingEnvironmentProfile,
    package_sha256,
)
from .store import OperationalStore

SCHEMA_BATTERY_REPORT = "ace.proposer_stage2.constitution_battery.v1"

EPISODE_FILES = (
    "EP1-G3-APPLICATION.txt",
    "EP2-ABC-V3.txt",
    "EP3-ROUND2-GATE.txt",
    "EP4-CONTROL-REGRESSION-ATTRIBUTION.txt",
    "EP5-G4-INHERITANCE.txt",
    "EP6-PER-TASK-RECORDING.txt",
)


class _DeterministicClock:
    def __init__(self, initial: float = 1_731_580_000.0):
        self.now = float(initial)

    def __call__(self) -> float:
        return self.now

    def advance(self, delta: float) -> float:
        self.now += float(delta)
        return self.now


def _load_frozen_stage1_v2_packages(repo_root: Path) -> list[dict[str, Any]]:
    base = repo_root / "evidence" / "proposer_stage1_v2" / "grammar_only"
    loaded: list[dict[str, Any]] = []
    for fname in EPISODE_FILES:
        path = base / fname
        raw = path.read_bytes()
        pkg = json.loads(raw.decode("utf-8"))
        loaded.append({
            "filename": fname,
            "relpath": str(path.relative_to(repo_root)),
            "file_sha256": hashlib.sha256(raw).hexdigest(),
            "file_size_bytes": len(raw),
            "package": pkg,
            "canonical_payload_sha256": package_sha256(pkg),
        })
    return loaded


def run_stage2_constitution_battery(repo_root: Path) -> dict[str, Any]:
    """Run all 7 Stage-2 constitutional checks in an isolated staging workspace."""
    repo_root = Path(repo_root).resolve()
    sources = _load_frozen_stage1_v2_packages(repo_root)
    by_name = {s["filename"]: s for s in sources}

    with tempfile.TemporaryDirectory(prefix="ace-stage2-battery-") as td:
        ws = Path(td) / "staging_ws"
        store = OperationalStore(ws)
        bus = MissionBus(ws / "mission_bus.sqlite3")
        clock = _DeterministicClock()
        engine = Stage2StagingEngine(store, mission_bus=bus, now_fn=clock)

        try:
            checks: list[dict[str, Any]] = []
            run_ids: list[str] = []

            # C1: EP1-G3-APPLICATION recommends "do_not_run" -> fail-closed refusal.
            ep1 = by_name["EP1-G3-APPLICATION.txt"]
            s1, _ = engine.stage_package(ep1["package"], request_id="bat-c1-ep1")
            engine.ratify_staged(s1["staging_id"], audience="hub", payload_sha256=s1["payload_sha256"], ttl_seconds=60)
            c1_blocked = False
            try:
                engine.dispatch_staged(s1["staging_id"], expected_payload_sha256=s1["payload_sha256"])
            except DoNotRunError:
                c1_blocked = True
            checks.append({
                "check_id": "C1_DO_NOT_RUN_BLOCK",
                "episode": ep1["filename"],
                "proposal_id": s1["proposal_id"],
                "payload_sha256": s1["payload_sha256"],
                "passed": bool(c1_blocked and len(engine.list_runs(s1["staging_id"])) == 0),
                "runs_created": len(engine.list_runs(s1["staging_id"])),
            })

            # C2: EP2-ABC-V3 — vocabulary firewall + wrong hash + expired TTL + valid staging dispatch.
            ep2 = by_name["EP2-ABC-V3.txt"]
            s2, s2_new = engine.stage_package(ep2["package"], request_id="bat-c2-ep2")
            _, s2_idem = engine.stage_package(ep2["package"], request_id="bat-c2-ep2")
            vocab_rejected = False
            hash_rejected = False
            ttl_rejected = False
            conflict_rejected = False
            try:
                engine.ratify_staged(s2["staging_id"], audience="owner_approval", payload_sha256=s2["payload_sha256"])
            except RatificationVocabularyError:
                vocab_rejected = True
            try:
                engine.ratify_staged(s2["staging_id"], audience="kernel", payload_sha256="0" * 64)
            except RatificationError:
                hash_rejected = True
            mutated = json.loads(json.dumps(ep2["package"]))
            mutated["claim"] = "Altered claim colliding on the same request_id must fail closed."
            try:
                engine.stage_package(mutated, request_id="bat-c2-ep2")
            except RequestConflictError:
                conflict_rejected = True
            engine.ratify_staged(s2["staging_id"], audience="kernel", payload_sha256=s2["payload_sha256"], ttl_seconds=5.0)
            clock.advance(5.0)
            try:
                engine.dispatch_staged(s2["staging_id"], expected_payload_sha256=s2["payload_sha256"])
            except RatificationError:
                ttl_rejected = True
            engine.ratify_staged(s2["staging_id"], audience="kernel", payload_sha256=s2["payload_sha256"], ttl_seconds=120.0)
            r2 = engine.dispatch_staged(s2["staging_id"], expected_payload_sha256=s2["payload_sha256"])
            run_ids.append(r2["execution_run_id"])
            checks.append({
                "check_id": "C2_HASH_PIN_VOCAB_AND_TTL",
                "episode": ep2["filename"],
                "proposal_id": s2["proposal_id"],
                "payload_sha256": s2["payload_sha256"],
                "passed": bool(
                    s2_new and (not s2_idem) and vocab_rejected and hash_rejected
                    and conflict_rejected and ttl_rejected and r2["status"] == "COMPLETED"
                    and r2["preaudit_exit_code"] == 0
                ),
                "execution_run_id": r2["execution_run_id"],
                "status": r2["status"],
                "preaudit_exit_code": r2["preaudit_exit_code"],
            })

            # C3: EP3-ROUND2-GATE — visible bounded stop + partial work/cost accounting + no_auto_retry.
            ep3 = by_name["EP3-ROUND2-GATE.txt"]
            s3, _ = engine.stage_package(ep3["package"], request_id="bat-c3-ep3")
            engine.ratify_staged(s3["staging_id"], audience="evidence", payload_sha256=s3["payload_sha256"], ttl_seconds=120.0)
            step1_ready = threading.Event()
            proceed_stop = threading.Event()
            c3_holder: dict[str, Any] = {}

            def worker_stop(ctx, _pkg):
                ctx.record_step(
                    step_name="step_partial",
                    calls=3,
                    cost_units=0.15,
                    work_units=2,
                    dummy_artifact_rel="ep3_partial.json",
                    dummy_content=b'{"partial":true}',
                )
                clock.advance(2.0)
                step1_ready.set()
                proceed_stop.wait(timeout=5.0)
                ctx.record_step(step_name="step_after_stop", calls=1, cost_units=0.1, work_units=1)

            t3 = threading.Thread(
                target=lambda: c3_holder.setdefault(
                    "run",
                    engine.dispatch_staged(
                        s3["staging_id"],
                        expected_payload_sha256=s3["payload_sha256"],
                        worker=worker_stop,
                    ),
                ),
                daemon=True,
            )
            t3.start()
            if not step1_ready.wait(timeout=5.0):
                raise TimeoutError("C3 worker did not reach stop checkpoint")
            active_id = engine.list_runs(s3["staging_id"])[0]["execution_run_id"]
            engine.request_stop(active_id, reason="battery_visible_stop")
            clock.advance(0.1)
            proceed_stop.set()
            t3.join(timeout=5.0)
            r3 = c3_holder["run"]
            run_ids.append(r3["execution_run_id"])
            retry_blocked = False
            try:
                engine.dispatch_staged(s3["staging_id"], expected_payload_sha256=s3["payload_sha256"])
            except AutoRetryBlockedError:
                retry_blocked = True
            checks.append({
                "check_id": "C3_VISIBLE_STOP_AND_NO_AUTO_RETRY",
                "episode": ep3["filename"],
                "proposal_id": s3["proposal_id"],
                "payload_sha256": s3["payload_sha256"],
                "passed": bool(
                    r3["status"] == "STOPPED" and r3["stop_visible"] and r3["calls_used"] == 3
                    and r3["work_completed_units"] == 2 and r3["preaudit_exit_code"] == 0
                    and retry_blocked
                ),
                "execution_run_id": r3["execution_run_id"],
                "status": r3["status"],
                "calls_used": r3["calls_used"],
                "cost_units": r3["cost_units"],
                "stop_latency_seconds": r3["result_summary"].get("stop_latency_seconds"),
                "preaudit_exit_code": r3["preaudit_exit_code"],
            })

            # C4: EP4-CONTROL-REGRESSION-ATTRIBUTION — hard ceiling enforcement + no_auto_retry.
            ep4_pkg = json.loads(json.dumps(by_name["EP4-CONTROL-REGRESSION-ATTRIBUTION.txt"]["package"]))
            ep4_pkg["cost_estimate"] = {"calls": 1, "wall_seconds": 10, "cost_units": 0.25}
            ep4_pkg["cost_ceiling"] = {"max_calls": 2, "max_wall_seconds": 60, "max_cost_units": 0.5}
            s4, _ = engine.stage_package(ep4_pkg, request_id="bat-c4-ep4")
            engine.ratify_staged(s4["staging_id"], audience="hub", payload_sha256=s4["payload_sha256"], ttl_seconds=120.0)

            def worker_ceiling(ctx, _pkg):
                ctx.record_step(step_name="within_budget", calls=2, cost_units=0.25, work_units=1)
                ctx.record_step(step_name="exceed_calls", calls=1, cost_units=0.1, work_units=1)

            r4 = engine.dispatch_staged(s4["staging_id"], expected_payload_sha256=s4["payload_sha256"], worker=worker_ceiling)
            run_ids.append(r4["execution_run_id"])
            c4_retry_blocked = False
            try:
                engine.dispatch_staged(s4["staging_id"], expected_payload_sha256=s4["payload_sha256"])
            except AutoRetryBlockedError:
                c4_retry_blocked = True
            checks.append({
                "check_id": "C4_HARD_CEILING_ABORT",
                "episode": "EP4-CONTROL-REGRESSION-ATTRIBUTION.txt",
                "proposal_id": s4["proposal_id"],
                "payload_sha256": s4["payload_sha256"],
                "passed": bool(
                    r4["status"] == "ABORTED_CEILING" and r4["calls_used"] == 2
                    and r4["preaudit_exit_code"] == 0 and c4_retry_blocked
                ),
                "execution_run_id": r4["execution_run_id"],
                "status": r4["status"],
                "stop_reason": r4["stop_reason"],
                "preaudit_exit_code": r4["preaudit_exit_code"],
            })

            # C5: EP5-G4-INHERITANCE — irrevocable mid-flight revocation + exact effective ledger seq.
            ep5 = by_name["EP5-G4-INHERITANCE.txt"]
            s5, _ = engine.stage_package(ep5["package"], request_id="bat-c5-ep5")
            engine.ratify_staged(s5["staging_id"], audience="hub", payload_sha256=s5["payload_sha256"], ttl_seconds=120.0)
            s5_step1 = threading.Event()
            s5_proceed = threading.Event()
            c5_holder: dict[str, Any] = {}

            def worker_revoked(ctx, _pkg):
                ctx.record_step(step_name="step1_ok", calls=1, cost_units=0.1, work_units=1)
                s5_step1.set()
                s5_proceed.wait(timeout=5.0)
                ctx.record_step(step_name="step2_must_halt", calls=1, cost_units=0.1, work_units=1)

            t5 = threading.Thread(
                target=lambda: c5_holder.setdefault(
                    "run",
                    engine.dispatch_staged(s5["staging_id"], expected_payload_sha256=s5["payload_sha256"], worker=worker_revoked),
                ),
                daemon=True,
            )
            t5.start()
            if not s5_step1.wait(timeout=5.0):
                raise TimeoutError("C5 worker did not reach revocation checkpoint")
            rev5 = engine.revoke_staged(s5["staging_id"], actor="evidence", reason="battery_midflight_revocation")
            s5_proceed.set()
            t5.join(timeout=5.0)
            r5 = c5_holder["run"]
            run_ids.append(r5["execution_run_id"])
            reratify_blocked = False
            try:
                engine.ratify_staged(s5["staging_id"], audience="kernel", payload_sha256=s5["payload_sha256"])
            except RevokedError:
                reratify_blocked = True
            checks.append({
                "check_id": "C5_IRREVOCABLE_MIDFLIGHT_REVOCATION",
                "episode": ep5["filename"],
                "proposal_id": s5["proposal_id"],
                "payload_sha256": s5["payload_sha256"],
                "passed": bool(
                    r5["status"] == "STOPPED"
                    and f"revoked_at_seq:{rev5['revocation_ledger_seq']}" in r5["stop_reason"]
                    and r5["calls_used"] == 1
                    and r5["preaudit_exit_code"] == 0
                    and reratify_blocked
                ),
                "execution_run_id": r5["execution_run_id"],
                "revocation_ledger_seq": rev5["revocation_ledger_seq"],
                "preaudit_exit_code": r5["preaudit_exit_code"],
            })

            # C6: EP6-PER-TASK-RECORDING — isolation boundary + intentional #8C replication.
            ep6 = by_name["EP6-PER-TASK-RECORDING.txt"]
            s6, _ = engine.stage_package(ep6["package"], request_id="bat-c6-ep6")
            engine.ratify_staged(s6["staging_id"], audience="evidence", payload_sha256=s6["payload_sha256"], ttl_seconds=120.0)
            live_rejected = False
            try:
                bad_env = StagingEnvironmentProfile(
                    identity_mode="production",
                    effective_identity="staging:test",
                    egress_blocked=True,
                    dummy_credentials_only=True,
                    dummy_credentials={"k": "dummy_1"},
                    dummy_resource_root=engine.dummy_base_dir / "ep6_bad",
                )
                engine.dispatch_staged(s6["staging_id"], expected_payload_sha256=s6["payload_sha256"], env_profile=bad_env)
            except EnvironmentIsolationError:
                live_rejected = True

            r6_a = engine.dispatch_staged(s6["staging_id"], expected_payload_sha256=s6["payload_sha256"])
            r6_b = engine.dispatch_staged(s6["staging_id"], expected_payload_sha256=s6["payload_sha256"])
            run_ids.extend([r6_a["execution_run_id"], r6_b["execution_run_id"]])
            recheck = preaudit_validator.validate(
                (Path(r6_b["bundle_dir"]) / "manifest.json").read_bytes(),
                Path(r6_b["bundle_dir"]) / "source",
            )
            checks.append({
                "check_id": "C6_ISOLATED_ENV_AND_8C_REPLICATION",
                "episode": ep6["filename"],
                "proposal_id": s6["proposal_id"],
                "payload_sha256": s6["payload_sha256"],
                "passed": bool(
                    live_rejected
                    and r6_a["status"] == "COMPLETED"
                    and r6_b["status"] == "COMPLETED"
                    and r6_a["execution_run_id"] != r6_b["execution_run_id"]
                    and r6_a["preaudit_exit_code"] == 0
                    and r6_b["preaudit_exit_code"] == 0
                    and recheck["summary_by_state"][preaudit_validator.TIDAK_SESUAI] == 0
                    and recheck["summary_by_state"][preaudit_validator.UNKNOWN] == 0
                ),
                "execution_run_ids": [r6_a["execution_run_id"], r6_b["execution_run_id"]],
                "enforcer_versions": r6_b["env_snapshot"]["enforcer_versions"],
            })

            # C7: #8C pre-commit immutable blob verification + full hash-chain integrity.
            def corrupt_blob(path: Path) -> None:
                os.chmod(path, 0o600)
                path.write_bytes(b'{"tampered":true}')

            blob_gate_blocked = False
            try:
                engine.stage_package(ep1["package"], request_id="bat-c7-corrupt", pre_commit_blob_hook=corrupt_blob)
            except BlobIntegrityError:
                blob_gate_blocked = True

            ledger_entries = engine.list_ledger()
            ledger_ok = engine.verify_ledger()
            bus_chain_ok = bus.verify_hash_chain()
            bus_eval_ok = bus.verify_evaluation_journal()
            unique_run_ids = len(set(run_ids)) == len(run_ids)

            checks.append({
                "check_id": "C7_BLOB_BEFORE_COMMIT_AND_CHAIN_AUDIT",
                "episode": "all",
                "passed": bool(blob_gate_blocked and ledger_ok and bus_chain_ok and bus_eval_ok and unique_run_ids),
                "ledger_entries": len(ledger_entries),
                "ledger_valid": ledger_ok,
                "mission_bus_hash_chain_valid": bus_chain_ok,
                "mission_bus_eval_journal_valid": bus_eval_ok,
                "unique_run_ids_count": len(run_ids),
            })

            all_passed = all(c["passed"] for c in checks)
            return {
                "schema": SCHEMA_BATTERY_REPORT,
                "identity_mode": "staging-only",
                "offline_zero_llm_calls": True,
                "source_packages": [
                    {
                        "filename": s["filename"],
                        "relpath": s["relpath"],
                        "file_sha256": s["file_sha256"],
                        "file_size_bytes": s["file_size_bytes"],
                        "proposal_id": s["package"]["proposal_id"],
                        "canonical_payload_sha256": s["canonical_payload_sha256"],
                    }
                    for s in sources
                ],
                "checks_total": len(checks),
                "checks_passed": sum(1 for c in checks if c["passed"]),
                "all_passed": all_passed,
                "checks": checks,
            }
        finally:
            store.close()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--repo-root",
        default=str(Path(__file__).resolve().parents[2]),
        help="ACE repository root containing evidence/proposer_stage1_v2/",
    )
    ap.add_argument("--out", default="", help="Optional path to write JSON report")
    args = ap.parse_args(argv)
    report = run_stage2_constitution_battery(Path(args.repo_root))
    rendered = json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    if args.out:
        out_path = Path(args.out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(rendered, encoding="utf-8")
    else:
        print(rendered, end="")
    return 0 if report["all_passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
